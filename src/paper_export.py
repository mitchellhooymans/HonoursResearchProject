"""Export the figures required by Context/AGNPaper/paper.tex.

Used by the export cell at the end of Paper_Results_Master.ipynb, Model_Validation_via_IRAC.ipynb and
CIGALE_Decomposition_Analysis.ipynb, so the three notebooks share one (safe) implementation.

Behaviour
---------
* Always copies each figure listed in ``config.PAPER_FIGURE_MANIFEST`` into ``outputs/PaperFigures/``.
* Copies into the paper's own ``Images/TheoreticalModelPlots/`` folder ONLY when
  ``config.COPY_FIGURES_INTO_PAPER`` is True (default False), so running a notebook can never silently
  replace the figures in the paper.
* When copying into the paper is enabled it is still conservative:
    - a figure is never overwritten if the file already in the paper is NEWER than the source
      (unless ``force=True``),
    - every file that is replaced is first backed up to
      ``Images/TheoreticalModelPlots/_export_backups/<timestamp>/``.
"""
import os
import shutil
import time

from . import config


def export_paper_figures(force=False):
    os.makedirs(config.PAPER_FIGURES_DIR, exist_ok=True)
    paper_present = os.path.isdir(config.AGNPAPER_DIR)
    to_paper = bool(getattr(config, 'COPY_FIGURES_INTO_PAPER', False)) and paper_present
    backup_dir = os.path.join(config.PAPER_OVERLEAF_IMAGES_DIR, '_export_backups', time.strftime('%Y%m%d_%H%M%S'))

    copied, missing = [], []
    replaced_in_paper, kept_newer_in_paper = [], []
    for name, rel_source in config.PAPER_FIGURE_MANIFEST.items():
        src = os.path.join(config.PROCESSED_DATA_DIR, rel_source)
        if not os.path.exists(src):
            missing.append(name)
            continue
        shutil.copy2(src, os.path.join(config.PAPER_FIGURES_DIR, name))
        copied.append(name)
        if not to_paper:
            continue
        dst = os.path.join(config.PAPER_OVERLEAF_IMAGES_DIR, name)
        if os.path.exists(dst):
            if os.path.getmtime(dst) > os.path.getmtime(src) and not force:
                kept_newer_in_paper.append(name)
                continue
            os.makedirs(backup_dir, exist_ok=True)
            shutil.copy2(dst, os.path.join(backup_dir, name))
        os.makedirs(config.PAPER_OVERLEAF_IMAGES_DIR, exist_ok=True)
        shutil.copy2(src, dst)
        replaced_in_paper.append(name)

    print(f"Paper figures exported to {config.PAPER_FIGURES_DIR}: {len(copied)}/{len(config.PAPER_FIGURE_MANIFEST)} copied")
    if paper_present and not to_paper:
        print("  The paper's Images folder was NOT touched (config.COPY_FIGURES_INTO_PAPER is False).")
        print("  Copy figures into the paper deliberately, from outputs/PaperFigures/.")
    if to_paper:
        print(f"  Copied into the paper: {len(replaced_in_paper)} figure(s); backups in {backup_dir}")
        for name in replaced_in_paper:
            print(f"    replaced {name}")
        for name in kept_newer_in_paper:
            print(f"    kept (paper copy is newer than the source): {name}")
    if missing:
        print("  Not yet generated by any notebook run:")
        for name in missing:
            print(f"    - {name}")
    else:
        print("  All paper-required figures present.")
    return copied, missing
